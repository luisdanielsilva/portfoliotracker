function log(msg) {
  console.log(`[migrate-snapshots] ${msg}`);
}

function migrateSnapshots() {
  log('🔄 Converting 74 hardcoded snapshots to database transactions...');

  const db = new Database(path.join(__dirname, 'data.db'));
  db.pragma('foreign_keys = ON');

  // Build holding history: ticker → [{date, qty}, ...]
  const holdings = {};
  BASE_RAW.forEach(snapshot => {
    const [dateStr, positions] = snapshot;
    const ts = new Date(dateStr).getTime();

    positions.forEach(pos => {
      const [tickerIdx, qty, amount] = pos;
      const ticker = TICKER_MAP[tickerIdx];
      if (!ticker) {
        log(`⚠ Unknown ticker index: ${tickerIdx}`);
        return;
      }

      if (!holdings[ticker]) holdings[ticker] = [];
      holdings[ticker].push({date: dateStr, ts, qty, amount});
    });
  });

  // Detect buy/sell transactions from qty changes
  const insertStmt = db.prepare(`
    INSERT INTO transactions (user_id, ticker, quantity, amount_eur, currency, exchange_rate, tx_type, ts)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?)
  `);

  let txCount = 0;
  const DEFAULT_USER_ID = 1;

  for (const [ticker, history] of Object.entries(holdings)) {
    // Sort by date
    history.sort((a, b) => a.ts - b.ts);

    let prevQty = 0;
    for (let i = 0; i < history.length; i++) {
      const {qty, amount, ts} = history[i];
      const qtyChange = qty - prevQty;

      if (qtyChange !== 0) {
        const txType = qtyChange > 0 ? 'buy' : 'sell';
        const quantity = Math.abs(qtyChange);

        // Calculate average price per share
        const pricePerShare = amount / qty;
        const txAmount = quantity * pricePerShare;

        try {
          insertStmt.run(DEFAULT_USER_ID, ticker, quantity, txAmount, 'EUR', 1.0, txType, ts);
          txCount++;
        } catch (err) {
          log(`❌ Error inserting transaction for ${ticker}: ${err.message}`);
        }
      }

      prevQty = qty;
    }
  }

  log(`✅ Migration complete: ${txCount} transactions created`);

  // Verify
  const checkStmt = db.prepare('SELECT COUNT(*) as count FROM transactions');
  const {count} = checkStmt.get();
  log(`📊 Total transactions in database: ${count}`);

  db.close();
}

migrateSnapshots();
